CREATE TABLE proveedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    email VARCHAR(200) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (CHAR_LENGTH(TRIM(email)) > 0 OR CHAR_LENGTH(TRIM(telefono)) > 0)
);

ALTER TABLE politica_reposicion ADD COLUMN proveedor_id BIGINT REFERENCES proveedor(id);
ALTER TABLE politica_reposicion ADD COLUMN canal_alerta VARCHAR(15);
ALTER TABLE politica_reposicion ADD CONSTRAINT ck_aviso_particular CHECK (
    (proveedor_id IS NULL AND canal_alerta IS NULL) OR
    (proveedor_id IS NOT NULL AND canal_alerta IS NOT NULL AND canal_alerta IN ('EMAIL', 'SMS', 'WHATSAPP'))
);

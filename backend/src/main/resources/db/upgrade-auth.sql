-- Actualización de esquema: autenticación y roles de sucursal.
-- Aplicar una vez después de upgrade-categorias.sql.
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE CHECK (CHAR_LENGTH(TRIM(username)) > 0),
    password_hash VARCHAR(255) NOT NULL CHECK (CHAR_LENGTH(TRIM(password_hash)) > 0),
    nombre_completo VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre_completo)) > 0),
    rol VARCHAR(30) NOT NULL CHECK (rol IN ('RECEPCION', 'REPOSITOR', 'COMPRAS', 'SUPERVISOR')),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);


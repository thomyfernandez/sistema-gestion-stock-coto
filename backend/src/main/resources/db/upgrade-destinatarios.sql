-- Actualización de esquema: listas de emails para avisos de stock bajo.
-- Aplicar después de upgrade-auth.sql. Es idempotente y no modifica asignaciones existentes:
-- mientras las listas estén vacías, los avisos siguen usando contacto del artículo, de la categoría o el general.
CREATE TABLE IF NOT EXISTS destinatario_aviso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    categoria_id INTEGER REFERENCES categoria(id),
    email VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(email)) > 0),
    CONSTRAINT uq_destinatario_categoria_email UNIQUE (categoria_id, email)
);
CREATE INDEX IF NOT EXISTS ix_destinatario_categoria ON destinatario_aviso(categoria_id);

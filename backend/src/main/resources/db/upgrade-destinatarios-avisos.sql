-- Actualización de esquema: destinatarios de avisos como listas de correos electrónicos.
-- Aplicar una vez después de upgrade-categorias.sql.
-- Desacopla los avisos de stock bajo de la política de reposición y los centraliza en listas general y por categoría.

CREATE TABLE IF NOT EXISTS destinatario_aviso (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    categoria_id INTEGER REFERENCES categoria(id),
    email VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(email)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_destinatario_general ON destinatario_aviso(email) WHERE categoria_id IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_destinatario_categoria ON destinatario_aviso(categoria_id, email) WHERE categoria_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_destinatario_categoria ON destinatario_aviso(categoria_id);

-- Flexibilización / eliminación de constraints particulares de política de reposición
ALTER TABLE politica_reposicion DROP CONSTRAINT IF EXISTS ck_aviso_particular;
ALTER TABLE politica_reposicion ALTER COLUMN destino_alerta DROP NOT NULL;

-- Migración idempotente de emails generales desde configuracion_avisos
INSERT INTO destinatario_aviso (categoria_id, email)
SELECT NULL, TRIM(email)
FROM configuracion_avisos
WHERE email IS NOT NULL AND CHAR_LENGTH(TRIM(email)) > 0
  AND NOT EXISTS (
      SELECT 1 FROM destinatario_aviso d
      WHERE d.categoria_id IS NULL AND LOWER(d.email) = LOWER(TRIM(configuracion_avisos.email))
  );

-- Migración idempotente de contactos de categorías que tengan email
INSERT INTO destinatario_aviso (categoria_id, email)
SELECT c.id, TRIM(p.email)
FROM categoria c
JOIN proveedor p ON p.id = c.contacto_id
WHERE p.email IS NOT NULL AND CHAR_LENGTH(TRIM(p.email)) > 0
  AND NOT EXISTS (
      SELECT 1 FROM destinatario_aviso d
      WHERE d.categoria_id = c.id AND LOWER(d.email) = LOWER(TRIM(p.email))
  );

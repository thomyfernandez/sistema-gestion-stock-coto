CREATE TABLE categoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    nombre_clave VARCHAR(80) NOT NULL UNIQUE,
    contacto_id BIGINT REFERENCES proveedor(id),
    canal_alerta VARCHAR(15),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK ((contacto_id IS NULL AND canal_alerta IS NULL) OR
        (contacto_id IS NOT NULL AND canal_alerta IS NOT NULL AND canal_alerta IN ('EMAIL', 'SMS', 'WHATSAPP')))
);
ALTER TABLE producto ADD COLUMN categoria_id INTEGER REFERENCES categoria(id);
CREATE INDEX ix_producto_categoria ON producto(categoria_id);


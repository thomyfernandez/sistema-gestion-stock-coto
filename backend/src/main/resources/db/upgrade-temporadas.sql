-- Actualización de esquema: temporadas de reposición estacional.
-- Aplicar después de upgrade-destinatarios.sql. Es idempotente: puede ejecutarse más de una vez.
--
-- Antes, la política ESTACIONAL guardaba un único factor que quedaba activo hasta que alguien lo cambiara.
-- Ahora el factor sale de temporadas con día y mes, para varios artículos o para una categoría. Para no cambiar
-- ningún pedido al migrar, cada política ESTACIONAL con factor distinto de 1 pasa a tener una temporada de ese
-- artículo que dura todo el año (01/01 al 31/12) con el mismo factor. Compras ajusta después las fechas reales.
-- Los factores de políticas de otro tipo no se usaban en ningún cálculo y se descartan.

CREATE TABLE IF NOT EXISTS temporada_reposicion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    -- Nula: la temporada es de los artículos de temporada_articulo (el dominio exige al menos uno).
    categoria_id INTEGER REFERENCES categoria(id),
    desde_mes INTEGER NOT NULL CHECK (desde_mes BETWEEN 1 AND 12),
    desde_dia INTEGER NOT NULL CHECK (desde_dia BETWEEN 1 AND 31),
    hasta_mes INTEGER NOT NULL CHECK (hasta_mes BETWEEN 1 AND 12),
    hasta_dia INTEGER NOT NULL CHECK (hasta_dia BETWEEN 1 AND 31),
    factor NUMERIC(6, 4) NOT NULL CHECK (factor > 0 AND factor <= 10)
);
CREATE INDEX IF NOT EXISTS ix_temporada_categoria ON temporada_reposicion(categoria_id);

-- Artículos de una temporada. La FK compuesta impide combos, igual que en politica_reposicion.
CREATE TABLE IF NOT EXISTS temporada_articulo (
    temporada_id BIGINT NOT NULL REFERENCES temporada_reposicion(id) ON DELETE CASCADE,
    stock_id INTEGER NOT NULL,
    tipo_stock VARCHAR(6) NOT NULL DEFAULT 'SIMPLE' CHECK (tipo_stock = 'SIMPLE'),
    PRIMARY KEY (temporada_id, stock_id),
    FOREIGN KEY (stock_id, tipo_stock) REFERENCES stock(id, tipo)
);
CREATE INDEX IF NOT EXISTS ix_temporada_articulo_stock ON temporada_articulo(stock_id);

-- En una segunda ejecución la columna ya no existe: se recrea con 1 para que la copia no encuentre filas.
ALTER TABLE politica_reposicion ADD COLUMN IF NOT EXISTS factor_estacional NUMERIC(12, 4) NOT NULL DEFAULT 1;
-- Columna auxiliar que vincula cada temporada migrada con su artículo; se elimina al final.
ALTER TABLE temporada_reposicion ADD COLUMN IF NOT EXISTS origen_migracion INTEGER;

-- Un factor mayor a 10 no entra en una temporada: se conserva el tope admitido.
INSERT INTO temporada_reposicion (nombre, desde_mes, desde_dia, hasta_mes, hasta_dia, factor, origen_migracion)
SELECT 'Factor anterior (todo el año)', 1, 1, 12, 31, LEAST(p.factor_estacional, 10), p.stock_id
FROM politica_reposicion p
WHERE p.tipo = 'ESTACIONAL' AND p.factor_estacional <> 1
  AND NOT EXISTS (SELECT 1 FROM temporada_articulo a WHERE a.stock_id = p.stock_id);
INSERT INTO temporada_articulo (temporada_id, stock_id)
SELECT t.id, t.origen_migracion FROM temporada_reposicion t WHERE t.origen_migracion IS NOT NULL;

ALTER TABLE temporada_reposicion DROP COLUMN IF EXISTS origen_migracion;
ALTER TABLE politica_reposicion DROP COLUMN IF EXISTS factor_estacional;

-- La política ESTACIONAL exige que el objetivo base por el factor máximo de una temporada (10) entre en un
-- entero. Un objetivo mayor, aceptado antes, impediría cargar las políticas: se limita al máximo admitido.
UPDATE politica_reposicion SET stock_objetivo = 214748364 WHERE tipo = 'ESTACIONAL' AND stock_objetivo > 214748364;

-- Aplicar una vez sobre una base inicializada con schema.sql + data.sql de la Etapa 1.
-- No elimina ni modifica productos, existencias, movimientos, pedidos o auditorías previas.
-- La configuración/promociones de ejemplo corresponden a los IDs de los datos de demostración.
-- Ejecutar con psql -v ON_ERROR_STOP=1 -1 para que toda la actualización sea atómica.
-- Dos filas de coordinación: inventario y despacho de integraciones. Sin entidad Sucursal.
CREATE TABLE bloqueo_operacion (id INTEGER PRIMARY KEY);

CREATE TABLE politica_reposicion (
    stock_id INTEGER PRIMARY KEY,
    tipo_stock VARCHAR(6) NOT NULL DEFAULT 'SIMPLE' CHECK (tipo_stock = 'SIMPLE'),
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('PUNTO_PEDIDO', 'DEMANDA', 'ESTACIONAL')),
    punto_pedido INTEGER NOT NULL CHECK (punto_pedido >= 0),
    stock_objetivo INTEGER NOT NULL CHECK (stock_objetivo > 0),
    demanda_diaria NUMERIC(12, 3) NOT NULL CHECK (demanda_diaria >= 0),
    dias_cobertura INTEGER NOT NULL CHECK (dias_cobertura > 0),
    factor_estacional NUMERIC(12, 4) NOT NULL CHECK (factor_estacional > 0),
    umbral_alerta INTEGER NOT NULL CHECK (umbral_alerta > 0),
    destino_alerta VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(destino_alerta)) > 0),
    alerta_activa BOOLEAN NOT NULL DEFAULT FALSE,
    FOREIGN KEY (stock_id, tipo_stock) REFERENCES stock(id, tipo),
    CHECK (tipo <> 'PUNTO_PEDIDO' OR (punto_pedido > 0 AND stock_objetivo > punto_pedido))
);

CREATE TABLE promocion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    producto_id INTEGER NOT NULL REFERENCES producto(id),
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('DESCUENTO', 'DOS_POR_UNO', 'MEDIO_PAGO')),
    porcentaje NUMERIC(7, 4) NOT NULL CHECK (porcentaje BETWEEN 0 AND 100),
    orden INTEGER NOT NULL CHECK (orden >= 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    medio_pago VARCHAR(60),
    UNIQUE (producto_id, orden),
    CHECK (tipo <> 'DOS_POR_UNO' OR porcentaje = 0),
    CHECK ((tipo = 'MEDIO_PAGO' AND medio_pago IS NOT NULL AND CHAR_LENGTH(TRIM(medio_pago)) > 0)
           OR (tipo <> 'MEDIO_PAGO' AND medio_pago IS NULL))
);

-- Outbox: se confirma junto con el movimiento/pedido y sólo se entrega tras el commit.
CREATE TABLE evento_integracion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    clave VARCHAR(150) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('STOCK_DIGITAL', 'ALERTA', 'PEDIDO_ERP')),
    stock_id INTEGER NOT NULL REFERENCES stock(id),
    pedido_id BIGINT REFERENCES pedido_reposicion(id),
    disponible INTEGER CHECK (disponible >= 0),
    canal VARCHAR(15) CHECK (canal IN ('EMAIL', 'SMS', 'WHATSAPP')),
    destino VARCHAR(200),
    texto VARCHAR(1000),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ENVIADO')),
    intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    ultimo_error VARCHAR(500),
    CHECK ((tipo = 'STOCK_DIGITAL' AND disponible IS NOT NULL)
           OR (tipo = 'ALERTA' AND canal IS NOT NULL AND destino IS NOT NULL AND texto IS NOT NULL)
           OR (tipo = 'PEDIDO_ERP' AND pedido_id IS NOT NULL))
);
CREATE INDEX ix_evento_pendiente ON evento_integracion(estado, id);


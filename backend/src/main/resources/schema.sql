-- SQL compatible con PostgreSQL y H2 en MODE=PostgreSQL.
-- Identidades desde 1000: los IDs 1..999 quedan disponibles para fixtures.
-- La identidad del stock coincide con la de su producto (relación 1:1, PK compartida).
CREATE TABLE producto (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    descripcion VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(descripcion)) > 0),
    precio NUMERIC(15, 2) NOT NULL CHECK (precio >= 0),
    imagen_version VARCHAR(64)
);

-- Composite: UNA tabla para toda la jerarquía. NO existe columna "disponible".
CREATE TABLE stock (
    id INTEGER PRIMARY KEY REFERENCES producto(id),
    tipo VARCHAR(6) NOT NULL CHECK (tipo IN ('SIMPLE', 'COMBO')),
    stock_fisico INTEGER,
    stock_exhibicion INTEGER,
    stock_reservado INTEGER,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT uq_stock_id_tipo UNIQUE (id, tipo),
    CONSTRAINT ck_stock_segun_tipo CHECK (
        (tipo = 'SIMPLE'
            AND stock_fisico IS NOT NULL AND stock_exhibicion IS NOT NULL AND stock_reservado IS NOT NULL
            AND stock_fisico >= 0 AND stock_exhibicion >= 0 AND stock_reservado >= 0
            AND CAST(stock_exhibicion AS BIGINT) + stock_reservado <= stock_fisico)
        OR
        (tipo = 'COMBO'
            AND stock_fisico IS NULL AND stock_exhibicion IS NULL AND stock_reservado IS NULL)
    )
);

CREATE TABLE linea_combo (
    combo_id INTEGER NOT NULL,
    tipo_combo VARCHAR(6) NOT NULL DEFAULT 'COMBO' CHECK (tipo_combo = 'COMBO'),
    componente_id INTEGER NOT NULL REFERENCES stock(id),
    cantidad_en_combo INTEGER NOT NULL CHECK (cantidad_en_combo > 0),
    PRIMARY KEY (combo_id, componente_id),
    CONSTRAINT fk_linea_padre_combo FOREIGN KEY (combo_id, tipo_combo) REFERENCES stock(id, tipo),
    CONSTRAINT ck_combo_no_autorreferencia CHECK (combo_id <> componente_id)
);
-- Los ciclos indirectos y la prohibición de publicar combos vacíos se validan en el dominio.
CREATE INDEX ix_linea_componente ON linea_combo(componente_id);

CREATE TABLE movimiento_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    stock_id INTEGER NOT NULL REFERENCES stock(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN (
        'RECEPCION', 'TRASLADO_A_GONDOLA', 'RETORNO_A_DEPOSITO', 'DEVOLUCION',
        'MERMA_DEPOSITO', 'MERMA_GONDOLA', 'RESERVA_DIGITAL', 'CANCELACION_RESERVA', 'DESPACHO_DIGITAL'
    )),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(motivo)) > 0),
    usuario VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(usuario)) > 0)
);
CREATE INDEX ix_movimiento_stock_fecha ON movimiento_stock(stock_id, fecha);

CREATE TABLE pedido_reposicion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    stock_id INTEGER NOT NULL,
    tipo_stock VARCHAR(6) NOT NULL DEFAULT 'SIMPLE' CHECK (tipo_stock = 'SIMPLE'),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    estado VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'RECIBIDO', 'CANCELADO')),
    CONSTRAINT fk_pedido_stock_simple FOREIGN KEY (stock_id, tipo_stock) REFERENCES stock(id, tipo)
);
CREATE INDEX ix_pedido_stock_estado ON pedido_reposicion(stock_id, estado);

CREATE TABLE auditoria_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    stock_id INTEGER NOT NULL REFERENCES stock(id),
    movimiento_id BIGINT REFERENCES movimiento_stock(id),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    disponible_anterior INTEGER CHECK (disponible_anterior >= 0),
    disponible_actual INTEGER NOT NULL CHECK (disponible_actual >= 0),
    detalle VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(detalle)) > 0)
);
CREATE INDEX ix_auditoria_stock_fecha ON auditoria_stock(stock_id, fecha);
-- Los valores de auditoría son snapshots históricos; el disponible vigente jamás se persiste en stock.

-- Dos filas de coordinación: inventario y despacho de integraciones. Sin entidad Sucursal.
CREATE TABLE bloqueo_operacion (id INTEGER PRIMARY KEY);

-- Agenda de contactos internos. Nombre físico legado para conservar instalaciones existentes.
CREATE TABLE proveedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    email VARCHAR(200) NOT NULL,
    telefono VARCHAR(30) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (CHAR_LENGTH(TRIM(email)) > 0 OR CHAR_LENGTH(TRIM(telefono)) > 0)
);

CREATE TABLE categoria (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(80) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    nombre_clave VARCHAR(80) NOT NULL UNIQUE,
    contacto_id BIGINT REFERENCES proveedor(id),
    canal_alerta VARCHAR(15),
    version BIGINT NOT NULL DEFAULT 0,
    CHECK ((contacto_id IS NULL AND canal_alerta IS NULL) OR
        (contacto_id IS NOT NULL AND canal_alerta IS NOT NULL AND canal_alerta IN ('EMAIL', 'SMS', 'WHATSAPP')))
);
ALTER TABLE producto ADD COLUMN categoria_id INTEGER REFERENCES categoria(id);
CREATE INDEX ix_producto_categoria ON producto(categoria_id);

CREATE TABLE politica_reposicion (
    stock_id INTEGER PRIMARY KEY,
    tipo_stock VARCHAR(6) NOT NULL DEFAULT 'SIMPLE' CHECK (tipo_stock = 'SIMPLE'),
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('PUNTO_PEDIDO', 'DEMANDA', 'ESTACIONAL')),
    punto_pedido INTEGER NOT NULL CHECK (punto_pedido >= 0),
    stock_objetivo INTEGER NOT NULL CHECK (stock_objetivo > 0),
    demanda_diaria NUMERIC(12, 3) NOT NULL CHECK (demanda_diaria >= 0),
    dias_cobertura INTEGER NOT NULL CHECK (dias_cobertura > 0),
    factor_estacional NUMERIC(12, 4) NOT NULL CHECK (factor_estacional > 0),
    umbral_alerta INTEGER NOT NULL CHECK (umbral_alerta > 0),
    destino_alerta VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(destino_alerta)) > 0),
    alerta_activa BOOLEAN NOT NULL DEFAULT FALSE,
    proveedor_id BIGINT REFERENCES proveedor(id),
    canal_alerta VARCHAR(15),
    CONSTRAINT ck_aviso_particular CHECK ((proveedor_id IS NULL AND canal_alerta IS NULL) OR
        (proveedor_id IS NOT NULL AND canal_alerta IS NOT NULL AND canal_alerta IN ('EMAIL', 'SMS', 'WHATSAPP'))),
    FOREIGN KEY (stock_id, tipo_stock) REFERENCES stock(id, tipo),
    CHECK (tipo <> 'PUNTO_PEDIDO' OR (punto_pedido > 0 AND stock_objetivo > punto_pedido))
);

CREATE TABLE promocion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    producto_id INTEGER NOT NULL REFERENCES producto(id),
    tipo VARCHAR(15) NOT NULL CHECK (tipo IN ('DESCUENTO', 'DOS_POR_UNO', 'MEDIO_PAGO')),
    porcentaje NUMERIC(7, 4) NOT NULL CHECK (porcentaje BETWEEN 0 AND 100),
    orden INTEGER NOT NULL CHECK (orden >= 0),
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    medio_pago VARCHAR(60),
    UNIQUE (producto_id, orden),
    CHECK (tipo <> 'DOS_POR_UNO' OR porcentaje = 0),
    CHECK ((tipo = 'MEDIO_PAGO' AND medio_pago IS NOT NULL AND CHAR_LENGTH(TRIM(medio_pago)) > 0)
           OR (tipo <> 'MEDIO_PAGO' AND medio_pago IS NULL))
);

-- Outbox: se confirma junto con el movimiento/pedido y sólo se entrega tras el commit.
CREATE TABLE evento_integracion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    clave VARCHAR(150) NOT NULL UNIQUE,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('STOCK_DIGITAL', 'ALERTA', 'PEDIDO_ERP')),
    stock_id INTEGER NOT NULL REFERENCES stock(id),
    pedido_id BIGINT REFERENCES pedido_reposicion(id),
    disponible INTEGER CHECK (disponible >= 0),
    canal VARCHAR(15) CHECK (canal IN ('EMAIL', 'SMS', 'WHATSAPP')),
    destino VARCHAR(200),
    texto VARCHAR(1000),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE', 'ENVIADO')),
    intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    ultimo_error VARCHAR(500),
    CHECK ((tipo = 'STOCK_DIGITAL' AND disponible IS NOT NULL)
           OR (tipo = 'ALERTA' AND canal IS NOT NULL AND destino IS NOT NULL AND texto IS NOT NULL)
           OR (tipo = 'PEDIDO_ERP' AND pedido_id IS NOT NULL))
);
CREATE INDEX ix_evento_pendiente ON evento_integracion(estado, id);

-- Destinatarios compartidos por todos los artículos de la sucursal.
CREATE TABLE configuracion_avisos (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    canal VARCHAR(15) NOT NULL CHECK (canal IN ('EMAIL', 'SMS', 'WHATSAPP')),
    email VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(email)) > 0),
    telefono VARCHAR(30) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK (canal = 'EMAIL' OR CHAR_LENGTH(TRIM(telefono)) > 0)
);

-- Bytes separados de producto para no cargar imágenes al consultar existencias.
CREATE TABLE imagen_producto (
    producto_id INTEGER PRIMARY KEY REFERENCES producto(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('image/png', 'image/jpeg')),
    contenido BYTEA NOT NULL CHECK (OCTET_LENGTH(contenido) BETWEEN 1 AND 2097152)
);

-- SQL compatible con PostgreSQL y H2 en MODE=PostgreSQL.
-- Identidades desde 1000: los IDs 1..999 quedan disponibles para fixtures.
-- La identidad del stock coincide con la de su producto (relación 1:1, PK compartida).
CREATE TABLE producto (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    nombre VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(TRIM(nombre)) > 0),
    descripcion VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(descripcion)) > 0),
    precio NUMERIC(15, 2) NOT NULL CHECK (precio >= 0)
);

-- Composite: UNA tabla para toda la jerarquía. NO existe columna "disponible".
CREATE TABLE stock (
    id INTEGER PRIMARY KEY REFERENCES producto(id),
    tipo VARCHAR(6) NOT NULL CHECK (tipo IN ('SIMPLE', 'COMBO')),
    stock_fisico INTEGER,
    stock_exhibicion INTEGER,
    stock_reservado INTEGER,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT uq_stock_id_tipo UNIQUE (id, tipo),
    CONSTRAINT ck_stock_segun_tipo CHECK (
        (tipo = 'SIMPLE'
            AND stock_fisico IS NOT NULL AND stock_exhibicion IS NOT NULL AND stock_reservado IS NOT NULL
            AND stock_fisico >= 0 AND stock_exhibicion >= 0 AND stock_reservado >= 0
            AND CAST(stock_exhibicion AS BIGINT) + stock_reservado <= stock_fisico)
        OR
        (tipo = 'COMBO'
            AND stock_fisico IS NULL AND stock_exhibicion IS NULL AND stock_reservado IS NULL)
    )
);

CREATE TABLE linea_combo (
    combo_id INTEGER NOT NULL,
    tipo_combo VARCHAR(6) NOT NULL DEFAULT 'COMBO' CHECK (tipo_combo = 'COMBO'),
    componente_id INTEGER NOT NULL REFERENCES stock(id),
    cantidad_en_combo INTEGER NOT NULL CHECK (cantidad_en_combo > 0),
    PRIMARY KEY (combo_id, componente_id),
    CONSTRAINT fk_linea_padre_combo FOREIGN KEY (combo_id, tipo_combo) REFERENCES stock(id, tipo),
    CONSTRAINT ck_combo_no_autorreferencia CHECK (combo_id <> componente_id)
);
-- Los ciclos indirectos y la prohibición de publicar combos vacíos se validan en el dominio.
CREATE INDEX ix_linea_componente ON linea_combo(componente_id);

CREATE TABLE movimiento_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    stock_id INTEGER NOT NULL REFERENCES stock(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN (
        'RECEPCION', 'TRASLADO_A_GONDOLA', 'RETORNO_A_DEPOSITO', 'DEVOLUCION',
        'MERMA_DEPOSITO', 'MERMA_GONDOLA', 'RESERVA_DIGITAL', 'CANCELACION_RESERVA', 'DESPACHO_DIGITAL'
    )),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(motivo)) > 0),
    usuario VARCHAR(100) NOT NULL CHECK (CHAR_LENGTH(TRIM(usuario)) > 0)
);
CREATE INDEX ix_movimiento_stock_fecha ON movimiento_stock(stock_id, fecha);

CREATE TABLE pedido_reposicion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    stock_id INTEGER NOT NULL,
    tipo_stock VARCHAR(6) NOT NULL DEFAULT 'SIMPLE' CHECK (tipo_stock = 'SIMPLE'),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    estado VARCHAR(10) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'ENVIADO', 'RECIBIDO', 'CANCELADO')),
    CONSTRAINT fk_pedido_stock_simple FOREIGN KEY (stock_id, tipo_stock) REFERENCES stock(id, tipo)
);
CREATE INDEX ix_pedido_stock_estado ON pedido_reposicion(stock_id, estado);

CREATE TABLE auditoria_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    stock_id INTEGER NOT NULL REFERENCES stock(id),
    movimiento_id BIGINT REFERENCES movimiento_stock(id),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    disponible_anterior INTEGER CHECK (disponible_anterior >= 0),
    disponible_actual INTEGER NOT NULL CHECK (disponible_actual >= 0),
    detalle VARCHAR(500) NOT NULL CHECK (CHAR_LENGTH(TRIM(detalle)) > 0)
);
CREATE INDEX ix_auditoria_stock_fecha ON auditoria_stock(stock_id, fecha);
-- Los valores de auditoría son snapshots históricos; el disponible vigente jamás se persiste en stock.

